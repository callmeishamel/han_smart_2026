-- -----------------------------------------------------------------------------
-- 3. 적재 결과 확인
-- -----------------------------------------------------------------------------
SELECT risk_type,
       COUNT(*) AS chunk_count
FROM   safety_chunks
GROUP  BY risk_type
ORDER  BY chunk_count DESC, risk_type;

SELECT COUNT(*) AS total_chunks FROM safety_chunks;


