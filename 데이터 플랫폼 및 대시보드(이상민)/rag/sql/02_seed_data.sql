-- 개요
--   현재 탐지 대상인 위험유형 전체에 대한 대응 절차를 적재한다.
--   이 데이터가 있어야 생성된 대응안에 실제 근거가 붙는다.
--   적재하지 않으면 에이전트가 내장 지침 경로로만 동작한다.
--
--   문서 구성
--     doc_id 1  산업안전보건기준에 관한 규칙 발췌
--     doc_id 2  정비작업 안전 절차 지침
--     doc_id 3  작업장 통로 및 차량 운행 관리 기준
--
--   위험유형 대응
--     PPE        안전모 미착용
--     fire       화재
--     machinery  차량·중장비, 장애물
--     access     작업자 접근
--     chemical   유해물질 누출
--     loto       정비 절차 (시각 탐지 대상 아님, 관리자 질의용)
--     fall       작업자 쓰러짐
--
--   반복 실행 시 중복 적재를 방지하기 위해 기존 데이터 존재 여부를 확인한다.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. 문서 원문
-- -----------------------------------------------------------------------------
INSERT INTO safety_documents (doc_id, title, source, doc_type)
VALUES
    (1, '산업안전보건기준에 관한 규칙 발췌', '국가법령정보센터', '법령'),
    (2, '정비작업 안전 절차 지침',          '안전보건공단',     '지침'),
    (3, '작업장 통로 및 차량 운행 관리 기준', '안전보건공단',     '지침')
ON CONFLICT (doc_id) DO NOTHING;

-- SERIAL 시퀀스를 수동 삽입한 최대값에 맞춘다.
-- 이후 자동 채번이 충돌하지 않도록 하기 위함이다.
SELECT setval('safety_documents_doc_id_seq',
              (SELECT COALESCE(MAX(doc_id), 1) FROM safety_documents));


