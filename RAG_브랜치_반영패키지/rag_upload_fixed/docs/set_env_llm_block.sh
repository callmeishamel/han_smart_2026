# ------------------------------------------------------------------------------
# UDP 수신 배선
# ------------------------------------------------------------------------------
# 현재 포트 배선입니다.
#
#     9999   비전 모듈 -> ROS2 브릿지
#     9998   비전 모듈 -> 대시보드 · DB / RAG 파이프라인
#     9091   미니맵
#
# RAG 파이프라인은 9998 을 받습니다. 9999 로 맞추면 ROS2 브릿지와
# 같은 포트를 두고 다투게 되어 한쪽만 패킷을 받습니다.
#
# 비전 모듈이 다른 PC(엣지 보드)에서 보내므로 바인드 주소는 0.0.0.0 입니다.
# 같은 PC 안에서만 시험할 때는 127.0.0.1 로 좁혀도 됩니다.
export PIPELINE_UDP_BIND=0.0.0.0
export DASHBOARD_UDP_PORT=9998


# ------------------------------------------------------------------------------
# 지식베이스 DB (운영 DB와 나눠 쓸 때만)
# ------------------------------------------------------------------------------
# 아래를 설정하지 않으면 지금까지처럼 SFP_DB_* 하나로 동작합니다.
# 단일 DB 구성이면 이 절은 통째로 건너뛰십시오.
#
# 나누는 이유는 pgvector 때문입니다. 확장은 서버 측 기능이라 postgres 가
# 도는 PC 에 설치해야 하는데, 팀 공용 DB 가 윈도우에 있으면 리눅스 빌드
# 절차가 맞지 않습니다. 지식베이스는 읽기 전용에 가깝고 대시보드가
# 조회하지도 않으므로, 리눅스 쪽 로컬 DB 에 두면 설치가 단순해집니다.
#
#     팀 공용 DB      patrol_logs, response_plans, event_logs
#     지식베이스 DB   safety_documents, safety_chunks,
#                     response_guidelines   + pgvector
#
# 생략한 항목은 같은 이름의 SFP_DB_* 값을 그대로 씁니다. 같은 서버의
# 다른 데이터베이스만 쓰려면 RAG_KB_NAME 하나만 설정하면 됩니다.
#
# export RAG_KB_HOST=localhost
# export RAG_KB_PORT=5432
# export RAG_KB_NAME=smart_factory_kb
# export RAG_KB_USER=postgres
# export RAG_KB_PASSWORD=
#
# 확인:
#     python3 rag/kb_config.py


# ------------------------------------------------------------------------------
# LLM 서버 (GEMMA 2B)
# ------------------------------------------------------------------------------
# 실행기에 따라 둘 중 하나만 남기십시오.
# 설정하지 않아도 파이프라인은 규칙 기반 문장으로 동작합니다.

# --- GPU 없는 경우: Ollama ---
export LLM_BASE_URL=http://localhost:11434/v1
export LLM_MODEL=gemma2:2b

# --- GPU 있는 경우: vLLM ---
# export LLM_BASE_URL=http://localhost:8000/v1
# export LLM_MODEL=google/gemma-2-2b-it

# 생성 타임아웃(초).
# CPU 추론은 첫 요청이 특히 느립니다. 기본값 60 으로는 끊기는 경우가 있어
# CPU 환경에서는 180 을 권장합니다.
export LLM_TIMEOUT=180

